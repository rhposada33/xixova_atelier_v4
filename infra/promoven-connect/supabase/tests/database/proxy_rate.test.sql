begin;
create extension if not exists pgtap with schema extensions;
grant usage on schema extensions to connect_proxy;
set local search_path=public,extensions;
select plan(12);
select ok(not has_function_privilege('anon','public.connect_proxy_rate(text)','execute'),'anon cannot consume trusted limiter');
select ok(not has_function_privilege('authenticated','public.connect_proxy_rate(text)','execute'),'authenticated cannot consume trusted limiter');
select ok(has_function_privilege('connect_proxy','public.connect_proxy_rate(text)','execute'),'proxy can consume limiter');
select ok(not has_table_privilege('connect_proxy','public.leads','select'),'proxy cannot read leads');
select ok(not has_table_privilege('connect_proxy','auth.users','select'),'proxy cannot read auth');
select ok(not has_table_privilege('connect_proxy','storage.objects','select'),'proxy cannot read storage');
select ok(not has_table_privilege('connect_proxy','private.connect_proxy_buckets','update'),'proxy cannot reset buckets');
set local role connect_proxy;
select throws_ok($$select public.connect_proxy_rate('invalid')$$,'22023','invalid_rate_key','invalid key rejected');
select ok(public.connect_proxy_rate(repeat('a',64)),'first accepted');
do $$begin perform public.connect_proxy_rate(repeat('a',64)) from generate_series(1,29);end$$;
select is(public.connect_proxy_rate(repeat('a',64)),false,'31st denied');
reset role;
update private.connect_proxy_buckets set window_start=clock_timestamp()-interval '61 seconds' where key=repeat('a',64);
set local role connect_proxy;
select ok(public.connect_proxy_rate(repeat('a',64)),'window reset after expiry');
reset role;
select is((select requests from private.connect_proxy_buckets where key=repeat('a',64)),1,'expiry resets count atomically');
select * from finish();
rollback;
